'use strict'

// Reference engines read original ZIP bytes, not product-generated expectations.
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto'), zlib = require('node:zlib')
const assert = require('node:assert/strict'), { spawnSync } = require('node:child_process')
const { zipMember, cases } = require('../tests/helpers/zip-integrity')
const { inspectZip, extractZipEntry } = require('../miniprogram/file-reader/engine/core/file-inspector')
const seven = require('../miniprogram/file-reader/archive/sevenzip-runtime')
const samples = require('../tests/fixtures/zip-integrity/samples.json')
const hash = b => crypto.createHash('sha256').update(b).digest('hex')
const root = path.resolve(__dirname, '..')
assert.ok(process.argv[2], 'Supply an existing task scratch directory')
const out = fs.mkdtempSync(path.join(path.resolve(process.argv[2]), 'zip-evidence-'))
const originals = samples.map(sample => ({ ...sample, bytes: fs.readFileSync(path.join(root, 'tests/fixtures/zip-integrity', sample.name)) }))
const generated = cases.flatMap(c => [
  { name: c.name, bytes: zipMember(c), expectedHash: hash(c.content), expectedSize: c.content.length },
  { name: c.name + '-bad-crc-zero', bytes: zipMember({ ...c, crc: 0 }), reject: true }
])
for (const method of [0, 8]) for (const content of [Buffer.alloc(0), Buffer.from('9d0ad96d', 'hex')]) {
  generated.push({ name: 'zero-crc-' + method + '-' + content.length, bytes: zipMember({ content, method }), expectedHash: hash(content), expectedSize: content.length })
}
const tasks = [...originals, ...generated]
const python = spawnSync(process.env.ZIP_PYTHON || 'python3', ['-c', `import sys,json,io,zipfile,base64,hashlib,platform
out=[]
for item in json.load(sys.stdin):
 rows=[]
 try:
  with zipfile.ZipFile(io.BytesIO(base64.b64decode(item['base64']))) as z:
   for e in z.infolist():
    try:
     b=z.read(e); rows.append(dict(name=e.filename,size=len(b),sha256=hashlib.sha256(b).hexdigest()))
    except Exception as x: rows.append(dict(name=e.filename,error=type(x).__name__+': '+str(x)))
  out.append(dict(name=item['name'],entries=rows))
 except Exception as x: out.append(dict(name=item['name'],error=type(x).__name__+': '+str(x)))
print(json.dumps(dict(version=platform.python_version(),results=out)))`], {
  input: JSON.stringify(tasks.map(t => ({ name: t.name, base64: t.bytes.toString('base64') }))),
  encoding: 'utf8', timeout: 30000, maxBuffer: 4 * 1024 * 1024
})
assert.equal(python.status, 0, python.stderr)
const reference = JSON.parse(python.stdout)

async function main () {
  const wasmBinary = zlib.brotliDecompressSync(fs.readFileSync(path.join(root, 'miniprogram/file-reader/sevenzip/runtime/7zz.wasm.br')))
  const options = { wasmBinary, archiveExtension: '.zip' }
  const results = []
  for (let i = 0; i < tasks.length; i++) {
    const task = tasks[i], ref = reference.results[i]
    assert.equal(ref.name, task.name)
    if (task.reject) {
      assert.match(ref.entries[0].error, /CRC/)
      const entry = inspectZip(task.bytes).entries[0]
      assert.throws(() => extractZipEntry(task.bytes, entry), /CRC/)
      results.push({ name: task.name, pythonError: ref.entries[0].error, readerRejected: true })
      continue
    }
    if (task.sha256) assert.equal(hash(task.bytes), task.sha256)
    if (task.readerError || task.recovered) {
      let recoveredEntries
      if (task.readerError) assert.throws(() => inspectZip(task.bytes), /恢复/)
      else {
        const inspection = inspectZip(task.bytes)
        assert.match(inspection.summary, /恢复/)
        recoveredEntries = inspection.entries.map(entry => {
          const data = extractZipEntry(task.bytes, entry)
          return { name: entry.name, size: data.length, sha256: hash(data) }
        })
        assert.deepEqual(recoveredEntries, task.entries)
        // Expected bytes are independently extracted from the unchanged stored
        // counterpart by Python, bsdtar and 7-Zip, not generated by the reader.
        assert.deepEqual(recoveredEntries, reference.results.find(r => r.name === 'bla-stored.zip').entries)
      }
      assert.ok(ref.error || ref.entries.some(entry => entry.error))
      const tar = spawnSync(process.env.ZIP_BSDTAR || 'bsdtar', ['-xOf', path.join(root, 'tests/fixtures/zip-integrity', task.name), '--', 'test1.xml'], { timeout: 10000 })
      assert.notEqual(tar.status, 0)
      // A native fatal archive error sets Node's exitCode; keep that real result
      // isolated rather than clearing it and disguising this process as success.
      const child = spawnSync(process.execPath, ['-e', `
        const fs=require('node:fs'),zlib=require('node:zlib'),r=require('./miniprogram/file-reader/archive/sevenzip-runtime');
        const wasmBinary=zlib.brotliDecompressSync(fs.readFileSync('./miniprogram/file-reader/sevenzip/runtime/7zz.wasm.br'));
        r.inspect7zArchive(fs.readFileSync(process.argv[1]),{wasmBinary,archiveExtension:'.zip'})
          .then(x=>console.log(JSON.stringify({entries:x.entries.map(e=>e.name)})))
          .catch(e=>{console.log(JSON.stringify({error:e.message}));process.exitCode=2})
      `, path.join(root, 'tests/fixtures/zip-integrity', task.name)], { cwd: root, encoding: 'utf8', timeout: 10000 })
      if (child.error) throw child.error
      const sevenResult = { exitCode: child.status, ...JSON.parse(child.stdout) }
      results.push({ name: task.name, inputSha256: hash(task.bytes), readerError: task.readerError, recoveredEntries, counterpartContentMatch: Boolean(task.recovered), python: ref, bsdtarError: tar.stderr.toString(), sevenZip: sevenResult, sameFileNativeExtractionPass: false })
      continue
    }
    const entries = inspectZip(task.bytes).entries
    const expected = task.entries || [{ name: entries[0].name, size: task.expectedSize, sha256: task.expectedHash }]
    assert.deepEqual(ref.entries, expected)
    for (let j = 0; j < entries.length; j++) {
      const output = extractZipEntry(task.bytes, entries[j])
      assert.equal(hash(output), expected[j].sha256)
      assert.equal(output.length, expected[j].size)
    }
    if (task.sha256) {
      const nativeEntries = (await seven.inspect7zArchive(task.bytes, options)).entries
      assert.equal(nativeEntries.length, expected.length)
      for (const e of nativeEntries) {
        const oracle = expected.find(x => x.name === e.name)
        assert.ok(oracle)
        const native = await seven.extract7zEntry(task.bytes, e, options)
        assert.equal(hash(native), oracle.sha256)
        const tar = spawnSync(process.env.ZIP_BSDTAR || 'bsdtar', ['-xOf', path.join(root, 'tests/fixtures/zip-integrity', task.name), '--', e.name], { timeout: 10000, maxBuffer: 1024 * 1024 })
        assert.equal(tar.status, 0, tar.stderr.toString())
        assert.equal(hash(tar.stdout), oracle.sha256)
      }
    }
    results.push({ name: task.name, inputSha256: hash(task.bytes), entries: ref.entries, pythonMatch: true, bsdtarAndSevenZipMatch: Boolean(task.sha256) })
  }
  const tarVersion = spawnSync(process.env.ZIP_BSDTAR || 'bsdtar', ['--version'], { encoding: 'utf8', timeout: 10000 })
  assert.equal(tarVersion.status, 0, tarVersion.stderr)
  const report = { testedAt: new Date().toISOString(), node: process.version, python: reference.version, bsdtar: tarVersion.stdout.trim(), sevenZipWasmSha256: hash(wasmBinary), publicOriginals: originals.length, publicNativeContentPasses: 3, recoveredWithCounterpartHashes: 2, damagedDescriptorsRejected: 2, generatedValid: 64, generatedCrcRejects: 60, results }
  fs.writeFileSync(path.join(out, 'report.json'), JSON.stringify(report, null, 2) + '\n')
  console.log(JSON.stringify({ out, ...report, results: undefined }, null, 2))
}
main().catch(error => { console.error(error); process.exitCode = 1 })
