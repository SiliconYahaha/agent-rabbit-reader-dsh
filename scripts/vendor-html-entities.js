'use strict'

// Import immutable public test/data files once; subsequent builds are offline.
const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const assert = require('node:assert/strict')
const root = path.resolve(__dirname, '..')
const fixtures = path.join(root, 'tests/fixtures/html-entities')
const sources = {
  'entities.json': 'd741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6',
  'entities.test': 'fe17483810a00247579f5f129ca9c007fbab6755ba839523e29aa9f8875f4085',
  'namedEntities.test': 'a7f0e59ff7653820330548776cb3031c18e45f5fd1481a9813d9c7acee89bd6e',
  'numericEntities.test': '679296c976252322ece27e2b113a5358a0aa3b0b8ecd2d6d9b365f9d1b0f9632'
}
if (process.argv[2]) fs.mkdirSync(fixtures, { recursive: true })
for (const [name, sha] of Object.entries(sources)) {
  const input = path.join(process.argv[2] ? path.resolve(process.argv[2]) : fixtures, name)
  const bytes = fs.readFileSync(input)
  assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'), sha, name)
  if (process.argv[2]) fs.writeFileSync(path.join(fixtures, name), bytes, { flag: 'wx' })
}
const source = JSON.parse(fs.readFileSync(path.join(fixtures, 'entities.json'), 'utf8'))
assert.equal(Object.keys(source).length, 2231)
const names = Object.fromEntries(Object.entries(source).map(([key, value]) => [key.slice(1), value.characters]))
const output = "'use strict'\n// Generated by scripts/vendor-html-entities.js from WHATWG entities.json.\n// Copyright WHATWG (Apple, Google, Mozilla, Microsoft). BSD-3-Clause; see html-entities.LICENSE.\nmodule.exports = " + JSON.stringify(names) + '\n'
fs.writeFileSync(path.join(root, 'miniprogram/file-reader/document/html-named-entities.js'), output)
console.log('Verified 2231 WHATWG names and 3 immutable html5lib test corpora; generated offline entity table')
