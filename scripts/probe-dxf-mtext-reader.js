'use strict'
const fs = require('node:fs'), path = require('node:path'), zlib = require('node:zlib'), crypto = require('node:crypto')
const assert = require('node:assert/strict')
const { readerPage } = require('../tests/helpers/reader-host')
const samples = require('../tests/fixtures/dxf-mtext/samples.json')
async function main () {
  const out = path.resolve(process.argv[2] || 'outputs/dxf-mtext/reader')
  fs.mkdirSync(out, { recursive: true })
  let bytes
  const host = readerPage({ getFileSystemManager: () => ({ readFile: o => o.success({ data: bytes }) }) })
  const rows = []
  try {
    for (const sample of [...samples.cases, ...samples.roleCases]) {
      bytes = zlib.gunzipSync(Buffer.from(sample.sourceGzipBase64, 'base64'))
      assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'), sample.sha256)
      host.openSelectedFile({ name: sample.name + '.dxf', path: '/fixture/input.dxf', size: bytes.length })
      await new Promise(setImmediate)
      const svg = host.data.inspectorPreviewSource ? Buffer.from(host.data.inspectorPreviewSource.split(',')[1], 'base64').toString() : ''
      if (svg) fs.writeFileSync(path.join(out, sample.name + '.svg'), svg)
      rows.push({ name: sample.name, case: sample.case, sha256: sample.sha256, authored: sample.authored || sample.content,
        nativePlain: sample.nativePlain ?? sample.plain, nativeFast: sample.nativeFast, nativeDecodedHelper: sample.nativeDecodedHelper,
        error: host.data.error, hasContent: host.data.hasContent, readerLabels: [...svg.matchAll(/<text[^>]*>(.*?)<\/text>/gs)].map(m => m[1]) })
    }
  } finally { host.detached() }
  const report = { testedAt: new Date().toISOString(), scope: '46 actual Node host opens of deterministic original DXF files. Native references are independently generated by ezdxf; malformed and caret/codepoint stage conflicts remain separate. No pass claim or WeChat proof.', rows }
  fs.writeFileSync(path.join(out, 'report.json'), JSON.stringify(report, null, 2) + '\n')
  console.log(JSON.stringify({ actualHostOpens: rows.length, report: path.join(out, 'report.json') }))
}
main().catch(error => { console.error(error); process.exitCode = 1 })
